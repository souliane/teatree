def _touching(sentinel: Path) -> bytes:
    return f'#!/bin/sh\n: > "{sentinel}"\nexit 0\n'.encode()


def _run_pre_push(repo: Path) -> subprocess.CompletedProcess[bytes]:
    """Invoke the installed shim the way git does — from the worktree root, with empty stdin."""
    return subprocess.run(
        [str(repo / ".git" / "hooks" / "pre-push"), "origin", "https://example.invalid/x.git"],
        cwd=repo,
        input=b"",
        capture_output=True,
        check=False,
    )


class TestAnOrphanLegacyIsNeitherDestroyedNorActivated:
    """`<name>.legacy` with no `<name>` beside it: two histories, one filesystem, no way to tell.

    Either prek migrated the operator's gate and the shim was later removed — reachable inside
    teatree itself, since `remove_stale_hooks` unlinks `<name>` and never touches
    `<name>.legacy` — or the operator broke the chain deliberately. Measured: `-f` DELETES the
    orphan, and a resurrected one really does execute on every push. So it is parked: the bytes
    survive, nothing dormant is made live, and the operator is told where it is.
    """

    def test_the_orphan_is_parked_and_named_never_put_back(self, repo: Path) -> None:
        _write_hook_bytes(repo, "pre-push.legacy", _HAND_WRITTEN_HOOK)

        lines = _install(repo)

        assert not (repo / ".git" / "hooks" / "pre-push.legacy").exists()
        assert _parked(repo, "pre-push.legacy").read_bytes() == _HAND_WRITTEN_HOOK
        assert not any(line.startswith("OK") for line in lines), lines
        assert any(str(_parked(repo, "pre-push.legacy")) in line for line in lines), lines

    def test_a_migrated_gate_is_still_restored_in_place(self, repo: Path) -> None:
        """THE control on the orphan decision.

        "`destination is None` always" passes the test above while silently ending
        preservation for every gate prek's own migration mode parked.
        """
        _write_hook_bytes(repo, "pre-push", _HAND_WRITTEN_HOOK)
        _prek_migrate(repo, "pre-push")
        legacy = repo / ".git" / "hooks" / "pre-push.legacy"
        assert legacy.read_bytes() == _HAND_WRITTEN_HOOK, "the fixture never reached prek's migration mode"
        _write_hook_bytes(repo, "pre-commit", _HAND_WRITTEN_PRE_COMMIT)

        lines = _install(repo)

        assert legacy.read_bytes() == _HAND_WRITTEN_HOOK
        assert hook_quarantine.pending(git_common_dir(repo)) == ()
        assert any(line.startswith("OK") for line in lines), lines

    def test_the_parked_orphan_does_not_run_on_a_push(self, repo: Path, tmp_path: Path) -> None:
        sentinel = tmp_path / "ORPHAN_RAN"
        _write_hook_bytes(repo, "pre-push.legacy", _touching(sentinel))

        _install(repo)
        completed = _run_pre_push(repo)

        assert not sentinel.exists(), f"the parked orphan executed on a push: {completed.stderr!r}"

    def test_a_migrated_gate_does_run_on_a_push(self, repo: Path, tmp_path: Path) -> None:
        """Its control: without it, a probe that never actually executes the shim passes vacuously."""
        sentinel = tmp_path / "MIGRATED_RAN"
        _write_hook_bytes(repo, "pre-push", _touching(sentinel))
        _prek_migrate(repo, "pre-push")
        _write_hook_bytes(repo, "pre-commit", _HAND_WRITTEN_PRE_COMMIT)

        _install(repo)
        completed = _run_pre_push(repo)

        assert sentinel.exists(), f"the restored gate never ran: {completed.stdout!r} {completed.stderr!r}"


class TestNoOkLineOverAnUnreadableQuarantine:
    """`OK` over a quarantine nothing could read is a success line about an unknown.

    The `quarantined is None` branch was reachable only by a permission denial, so a mutation
    collapsing it into the `== ()` one survived every test in the suite.
    """

    def test_an_unreadable_quarantine_still_refuses_to_say_ok(self, repo: Path) -> None:
        _quarantine(repo).write_bytes(b"a regular file where the quarantine dir belongs")
