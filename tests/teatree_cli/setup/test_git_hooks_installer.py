_MINIMAL_PREK_CONFIG = """\
default_install_hook_types: [pre-commit, pre-push]
repos:
-   repo: local
    hooks:
    -   id: noop
        name: noop
        language: system
        entry: "true"
        pass_filenames: false
        always_run: true
"""

_PREK_BIN = shutil.which("prek") or "prek"

pytestmark = pytest.mark.skipif(shutil.which("prek") is None, reason="prek is not on PATH")


def make_prek_checkout(path: Path) -> Path:
    checkout = make_git_repo(path)
    (checkout / ".pre-commit-config.yaml").write_text(_MINIMAL_PREK_CONFIG, encoding="utf-8")
    return checkout


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    return make_prek_checkout(tmp_path / "repo")


#: A prek-generated hook whose baked binary belongs to another checkout — present,
#: executable there, and unrunnable on this platform.
_FOREIGN_PREK = "/elsewhere/another-worktree/.venv/bin/prek"

_BAKED_FOREIGN_HOOK = f"""#!/bin/sh
# File generated by prek: https://github.com/j178/prek
# ID: feedface

HERE="$(cd "$(dirname "$0")" && pwd)"
PREK="{_FOREIGN_PREK}"

exec "$PREK" hook-impl --hook-dir "$HERE" --script-version 4 --hook-type=pre-push -- "$@"
"""


def _install(*checkouts: Path) -> list[str]:
    lines: list[str] = []
    GitHooksInstaller(checkouts[0], checkouts=list(checkouts)).install(echo=lines.append)
    return lines


class TestGitHooksInstaller:
    def test_fresh_checkout_ends_with_both_hooks_installed(self, repo: Path) -> None:
        assert probe_git_hooks(repo).missing == REQUIRED_HOOK_NAMES

        lines = _install(repo)

        assert probe_git_hooks(repo).ok
        for name in REQUIRED_HOOK_NAMES:
            assert (repo / ".git" / "hooks" / name).is_file()
        assert any(line.startswith("OK") and "installed git hooks" in line for line in lines)

    def test_an_unprotected_second_clone_is_installed_into_as_well(self, tmp_path: Path) -> None:
        """The container/host split: one clone protected, the other silently not."""
        container = make_prek_checkout(tmp_path / "container-clone")
        host = make_prek_checkout(tmp_path / "host-checkout")
        _install(container)
        assert probe_git_hooks(host).missing == REQUIRED_HOOK_NAMES

        _install(container, host)

        assert probe_git_hooks(host).ok
        assert probe_git_hooks(container).ok

    def test_rerun_is_a_no_op(self, repo: Path) -> None:
        _install(repo)
        hooks = {name: (repo / ".git" / "hooks" / name).read_bytes() for name in REQUIRED_HOOK_NAMES}

        lines = _install(repo)

        for name, body in hooks.items():
            assert (repo / ".git" / "hooks" / name).read_bytes() == body
        assert any("already installed" in line for line in lines)
        assert not any(line.startswith("WARN") for line in lines)

    def test_an_existing_hook_baked_with_another_checkouts_binary_is_hardened(self, repo: Path) -> None:
        # `probe.ok` answers "is the hook PRESENT?", and a hook baked with a
        # sibling worktree's macOS venv IS present — it just dies
        # `Exec format error` inside the Linux worker. Returning early on `ok` is
        # why no re-run ever reached it.
        _install(repo)
        hook = probe_git_hooks(repo).hooks_dir / "pre-push"
        hook.write_text(_BAKED_FOREIGN_HOOK, encoding="utf-8")

        lines = _install(repo)

        surviving = hook.read_text()
        assert _FOREIGN_PREK not in surviving, f"a foreign baked path survived a re-run:\n{surviving}"
        assert "hook-impl" in surviving, "the repair must not destroy the dispatch line"
        assert any("re-hardened git hooks (pre-push)" in line for line in lines), (
            f"a silent repair still reported as a no-op:\n{lines}"
        )
        assert not any("already installed" in line for line in lines)

    def test_a_shim_bound_to_a_nested_config_is_repaired(self, repo: Path) -> None:
        """The whole point of `drop_foreign_config_hooks`, reachable only if the probe reports a gap."""
        _install(repo)
        shim = repo / ".git" / "hooks" / "pre-commit"
        shim.write_text(
            shim.read_text(encoding="utf-8").replace("hook-impl", 'hook-impl --cd="vendor/core"'), encoding="utf-8"
        )

        _install(repo)

        assert "--cd=" not in shim.read_text(encoding="utf-8")
        assert probe_git_hooks(repo).ok

    def test_deliberate_hooks_path_is_left_untouched(self, repo: Path, tmp_path: Path) -> None:
        elsewhere = tmp_path / "operator-hooks"
        elsewhere.mkdir()
        run_git(repo, "config", "core.hooksPath", str(elsewhere))

        lines = _install(repo)

        assert list(elsewhere.iterdir()) == []
        assert not (repo / ".git" / "hooks" / "pre-push").is_file()
        assert run_git(repo, "config", "--get", "core.hooksPath") == str(elsewhere)
        assert any(str(elsewhere) in line for line in lines)

    def test_checkout_without_a_prek_config_is_skipped(self, tmp_path: Path) -> None:
        plain = make_git_repo(tmp_path / "no-config")

        lines = _install(plain)

        assert any("No prek-managed checkout found" in line for line in lines)
        assert probe_git_hooks(plain).missing == REQUIRED_HOOK_NAMES

    def test_non_repo_warns_and_continues(self, tmp_path: Path) -> None:
        (tmp_path / ".pre-commit-config.yaml").write_text(_MINIMAL_PREK_CONFIG, encoding="utf-8")

        lines = _install(tmp_path)

        assert any(line.startswith("WARN") and "not a git checkout" in line for line in lines)

    @pytest.mark.parametrize(
        "gitdir",
        ["/another/venue/repo/.git/worktrees/linked-checkout", "../owner/.git/worktrees/linked-checkout"],
    )
    def test_linked_checkout_unavailable_in_this_venue_is_not_called_broken(self, tmp_path: Path, gitdir: str) -> None:
        foreign = tmp_path / "linked-checkout"
        foreign.mkdir()
        pointer = f"gitdir: {gitdir}\n"
        (foreign / ".git").write_text(pointer)
        (foreign / ".pre-commit-config.yaml").write_text(_MINIMAL_PREK_CONFIG, encoding="utf-8")

        lines = _install(foreign)

        assert len(lines) == 1
        assert lines[0].startswith("INFO")
        assert "unavailable in this venue" in lines[0]
        assert "parked-hook" not in lines[0]
        assert (foreign / ".git").read_text() == pointer


_INVALID_START_BYTE = "invalid start byte"


class TestOneBadCheckoutDoesNotUngateTheRest:
    """The loop installs into EVERY checkout, so a per-checkout failure must not escape it.

    A hooks dir holds whatever the filesystem put there — a `.DS_Store`, a hook owned by
    another user, a read-only dir. One raise aborted the loop, leaving every checkout
    AFTER it ungated, and `prepare_claude_runtime` runs `t3 setup` under `set -e`, so
    container init died on the traceback.
    """

    def test_a_raising_checkout_warns_and_the_next_one_is_still_installed(self, tmp_path: Path) -> None:
        poisoned = make_prek_checkout(tmp_path / "poisoned")
        healthy = make_prek_checkout(tmp_path / "healthy")
        _install(poisoned)  # so the second run takes the `probe.ok` short-circuit
        real_harden = git_hooks_installer.prek_hook.harden_hooks

        def _raise_for_the_poisoned_one(wt_path: str) -> list[Path]:
            if Path(wt_path) == poisoned:
                undecodable = UnicodeDecodeError("utf-8", b"\xff", 0, 1, _INVALID_START_BYTE)
                raise undecodable
            return real_harden(wt_path)

        with patch.object(git_hooks_installer.prek_hook, "harden_hooks", _raise_for_the_poisoned_one):
            lines = _install(poisoned, healthy)

        assert probe_git_hooks(healthy).ok, "the checkout after the failing one was left ungated"
        assert any(line.startswith("WARN") and str(poisoned) in line for line in lines)

    def test_junk_in_the_hooks_dir_is_not_a_failure_at_all(self, repo: Path) -> None:
        """The concrete case: the widened read now skips the junk instead of raising."""
        _install(repo)
        hooks_dir = probe_git_hooks(repo).hooks_dir
        (hooks_dir / ".DS_Store").write_bytes(b"\x00\x00\x00\x01Bud1\xff\xfe")

        lines = _install(repo)

        assert not any(line.startswith("WARN") for line in lines), lines
        assert probe_git_hooks(repo).ok
        assert (hooks_dir / ".DS_Store").is_file()


#: A prek shim gating the repo on a subdirectory's config — present and executable, so
#: the probe reports it missing and `install` reaches the drop that removes it.
_FOREIGN_CONFIG_SHIM = """#!/bin/sh
# File generated by prek: https://github.com/j178/prek
# ID: cafebabe

exec prek hook-impl --cd="vendor/core" --hook-type={name} -- "$@"
"""

_FOREIGN_SHIM_TYPES = ("commit-msg", "pre-commit", "pre-merge-commit", "pre-push")


def _write_foreign_config_shims(repo: Path) -> Path:
    hooks_dir = repo / ".git" / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    for name in _FOREIGN_SHIM_TYPES:
        shim = hooks_dir / name
        shim.write_text(_FOREIGN_CONFIG_SHIM.format(name=name), encoding="utf-8")
        shim.chmod(0o755)
    return hooks_dir


def _unlink_failing_on_call(nth: int) -> Callable[..., None]:
    real = Path.unlink
    calls: list[Path] = []

    def _unlink(self: Path, *args: object, **kwargs: object) -> None:
        calls.append(self)
        if len(calls) == nth:
            raise PermissionError(13, "Permission denied", str(self))
        real(self, *args, **kwargs)

    return _unlink


def _restore_that_fails(self: object) -> None:
    raise OSError(30, "Read-only file system")


def _prek_install_failing() -> Callable[..., StepResult]:
    """Fail the `prek install` step alone; every git step the behaviour depends on still runs."""
    real = git_hooks_installer.prek_hook.run_step

    def _dispatch(name: str, *args: object, **kwargs: object) -> StepResult:
        if name == "prek-install":
            return StepResult(name=name, success=False, error="prek exploded")
        return real(name, *args, **kwargs)

    return _dispatch


class TestTheFailureLineSaysWhatTheCheckoutIs:
    """`skipping; setup continues` is a claim about intent; the operator needs one about state.

    The install reaches destructive steps before it can fail, so one raise covers both a
    clone left exactly as found and a clone left with no commit or push gate at all. The
    line printed the same reassuring sentence for both, at exit 0.
    """

    def test_the_operator_line_says_the_clone_is_ungated_when_the_drop_could_not_be_undone(self, repo: Path) -> None:
        _write_foreign_config_shims(repo)

        with (
            patch.object(Path, "unlink", _unlink_failing_on_call(2)),
            patch.object(git_hooks_installer.prek_hook.DroppedHook, "restore", _restore_that_fails),
        ):
            lines = _install(repo)

        assert probe_git_hooks(repo).missing, "the fixture no longer leaves the clone ungated"
        line = "\n".join(lines)
        assert "skipping" not in line
        assert any(one.startswith("ERROR") for one in lines), lines
        assert str(repo) in line
        for name in probe_git_hooks(repo).missing:
            assert name in line

    def test_a_failed_install_still_preserves_what_it_already_overwrote(self, repo: Path) -> None:
        """`prek install -f` writes type by type and stops at the first it cannot — measured, exit 2.

        Everything it overwrote before that point is already destroyed, so a preservation
        reached only on the success path is the one the operator needed and did not get.
        """
        _write_hook_bytes(repo, "pre-commit", _HAND_WRITTEN_PRE_COMMIT)
        (repo / ".git" / "hooks" / "pre-push").mkdir()

        lines = _install(repo)

        assert (repo / ".git" / "hooks" / "pre-commit.legacy").read_bytes() == _HAND_WRITTEN_PRE_COMMIT
        assert any(line.startswith("WARN") and "`prek install` failed" in line for line in lines), lines

    def test_a_failed_install_that_overwrote_nothing_writes_no_copy(self, repo: Path) -> None:
        """The control: an unconditional preservation leaves a duplicate behind every failed run."""
        _write_hook_bytes(repo, "pre-commit", _HAND_WRITTEN_PRE_COMMIT)

        with patch.object(git_hooks_installer.prek_hook, "run_step", side_effect=_prek_install_failing()):
            lines = _install(repo)

        assert not list((repo / ".git" / "hooks").glob("*.legacy"))
        assert any(line.startswith("WARN") and "`prek install` failed" in line for line in lines), lines

    def test_an_install_that_landed_before_the_repair_raised_says_so(self, repo: Path) -> None:
        """The third arm: a re-probe alone cannot separate "nothing happened" from "post-steps failed".

        `_ensure_installed` reaches `prek_hook.install` only on a gap, and a FAILED install
        returns rather than raises — so a raise with a gap BEFORE and none after means the
        install landed and a step after it did not.
        """
        assert probe_git_hooks(repo).missing == REQUIRED_HOOK_NAMES

        undecodable = UnicodeDecodeError("utf-8", b"\xff", 0, 1, _INVALID_START_BYTE)

        def _raise(wt_path: str) -> list[Path]:
            raise undecodable

        with patch.object(git_hooks_installer.prek_hook, "harden_hooks", _raise):
            lines = _install(repo)

        line = "\n".join(lines)
        assert "left as found" not in line, lines
        assert not any(one.startswith("ERROR") for one in lines), lines
        assert "post-install repair did not complete" in line, lines
        assert "t3 setup" in line, lines
        assert probe_git_hooks(repo).ok

    def test_a_raise_with_no_destruction_still_reports_left_as_found(self, repo: Path) -> None:
        """The control without which the test above passes under a line that ERRORs on everything."""
        _install(repo)

        undecodable = UnicodeDecodeError("utf-8", b"\xff", 0, 1, _INVALID_START_BYTE)

        def _raise(wt_path: str) -> list[Path]:
            raise undecodable

        with patch.object(git_hooks_installer.prek_hook, "harden_hooks", _raise):
            lines = _install(repo)

        line = "\n".join(lines)
        assert "left as found" in line, lines
        assert not any(one.startswith("ERROR") for one in lines), lines
        assert probe_git_hooks(repo).ok


#: A legacy hook nobody wrote as UTF-8 — the `.git/hooks` any long-lived clone may hold.
_LATIN1_HOOK = "#!/bin/sh\n# caf\xe9 legacy hook\nexit 0\n".encode("latin-1")

#: A gate an operator wrote by hand. prek did not write it, and nothing else will.
_HAND_WRITTEN_HOOK = b"#!/bin/sh\n# the operator's own pre-push gate\nexit 0\n"

#: A second hand-written gate, distinct from the one above so two preserved copies cannot be
#: mistaken for one another.
_HAND_WRITTEN_PRE_COMMIT = b"#!/bin/sh\n# the operator's own pre-commit gate\nexit 0\n"


def _write_hook_bytes(repo: Path, name: str, blob: bytes) -> Path:
    hook = repo / ".git" / "hooks" / name
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_bytes(blob)
    hook.chmod(0o755)
    return hook


class TestAnUnreadableHookIsNeverReportedInstalled:
    """`t3 setup` printed `already installed` over a checkout with no working push gate.

    An undecodable `pre-push` exhibits no detectable fault, so the probe counted it
    installed and the repair keyed off that verdict never ran. The leak gate and
    `dev/push-gate.sh` stayed dark for every worktree of the clone, permanently.
    """

    def test_an_undecodable_pre_push_is_not_reported_already_installed(self, repo: Path) -> None:
        _install(repo)
        hook = _write_hook_bytes(repo, "pre-push", _LATIN1_HOOK)

        lines = _install(repo)

        assert not any("already installed" in line for line in lines), lines
        assert any("installed git hooks" in line for line in lines), lines
        assert probe_git_hooks(repo).ok
        body = hook.read_text(encoding="utf-8")
        assert "File generated by prek" in body

    def test_a_hand_written_hook_is_parked_as_legacy_not_destroyed(self, repo: Path) -> None:
        """`prek install -f` destroys what prek did not write, and this probe now triggers it."""
        hook = _write_hook_bytes(repo, "pre-push", _HAND_WRITTEN_HOOK)

        _install(repo)

        legacy = repo / ".git" / "hooks" / "pre-push.legacy"
        assert legacy.is_file(), "the operator's own gate was destroyed by the reinstall"
        assert legacy.read_bytes() == _HAND_WRITTEN_HOOK
        assert os.access(legacy, os.X_OK)
        assert "File generated by prek" in hook.read_text(encoding="utf-8")
        assert probe_git_hooks(repo).ok

    def test_an_undecodable_hook_is_parked_too_never_simply_gone(self, repo: Path) -> None:
        """The bytes nothing could read are still the operator's, and prek `-f` unlinks them."""
        _write_hook_bytes(repo, "pre-push", _LATIN1_HOOK)

        _install(repo)

        legacy = repo / ".git" / "hooks" / "pre-push.legacy"
        assert legacy.is_file(), "an unreadable hook was deleted rather than parked"
        assert legacy.read_bytes() == _LATIN1_HOOK

    def test_a_shim_bound_to_a_nested_config_produces_no_legacy_copy(self, repo: Path) -> None:
        """A prek shim is prek's, so the repair that replaces it preserves nothing.

        The repair has to actually run, so one shim is bound to a nested config — that is what
        makes the probe report a gap and sends `_ensure_installed` into `prek_hook.install`.
        """
        _install(repo)
        shim = repo / ".git" / "hooks" / "pre-commit"
        shim.write_text(
            shim.read_text(encoding="utf-8").replace("hook-impl", 'hook-impl --cd="vendor/core"'), encoding="utf-8"
        )
        assert probe_git_hooks(repo).missing == ("pre-commit",)

        _install(repo)

        assert not list((repo / ".git" / "hooks").glob("*.legacy"))
        assert probe_git_hooks(repo).ok

    def test_only_the_hook_prek_actually_overwrote_is_preserved(self, repo: Path) -> None:
        """Preserving whatever was captured duplicates every hook of every uninstalled type.

        `commit-msg` is that control precisely because the config declares only `pre-commit`
        and `pre-push`, so `prek install -f` never writes it — measured on prek 0.4.11, which
        reaps `<name>.legacy` only for the types it installs.
        """
        assert "default_install_hook_types: [pre-commit, pre-push]" in _MINIMAL_PREK_CONFIG
        assert "commit-msg" not in _MINIMAL_PREK_CONFIG
        hooks = repo / ".git" / "hooks"
        commit_msg = _write_hook_bytes(repo, "commit-msg", _HAND_WRITTEN_PRE_COMMIT)
        _write_hook_bytes(repo, "pre-push", _HAND_WRITTEN_HOOK)
        assert prek_hook._installable_hook_types(str(repo)) == ("pre-commit", "pre-push")

        _install(repo)

        assert sorted(path.name for path in hooks.glob("*.legacy")) == ["pre-push.legacy"]
        assert commit_msg.read_bytes() == _HAND_WRITTEN_PRE_COMMIT
        assert probe_git_hooks(repo).ok

    def test_doctor_fails_on_an_undecodable_pre_push(self, repo: Path) -> None:
        _install(repo)
        assert self._doctor_verdict(repo) is True

        _write_hook_bytes(repo, "pre-push", _LATIN1_HOOK)

        assert self._doctor_verdict(repo) is False

    @staticmethod
    def _doctor_verdict(repo: Path) -> bool:
        with patch("teatree.core.gates.git_checkouts.discover_checkouts", return_value=[repo]):
            return checks_bootstrap._check_git_hooks_installed()


