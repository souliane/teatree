def _prek_migrate(repo: Path, hook_type: str) -> None:
    """Plain `prek install -t <type>` — the migration mode that parks the operator's gate live."""
    subprocess.run([_PREK_BIN, "install", "-t", hook_type], cwd=repo, check=True, capture_output=True)


class TestAPreExistingLegacyGateSurvivesTheRepair:
    """`<name>.legacy` is a live dispatch slot, and `prek install -f` unlinks it.

    Migration mode parks the operator's gate there and the shim it installs RUNS it, so a
    capture that takes only `<name>` leaves the still-firing gate to be deleted by the very
    repair that exists to leave the checkout no weaker than it was found.
    """

    def test_the_migrated_gate_and_a_hand_written_hook_both_survive(self, repo: Path) -> None:
        _write_hook_bytes(repo, "pre-push", _HAND_WRITTEN_HOOK)
        _prek_migrate(repo, "pre-push")
        legacy = repo / ".git" / "hooks" / "pre-push.legacy"
        assert legacy.read_bytes() == _HAND_WRITTEN_HOOK, "the fixture never reached prek's migration mode"
        _write_hook_bytes(repo, "pre-commit", _HAND_WRITTEN_PRE_COMMIT)
        assert probe_git_hooks(repo).missing == ("pre-commit",)

        _install(repo)

        assert legacy.read_bytes() == _HAND_WRITTEN_HOOK, "the operator's migrated gate was deleted by the repair"
        assert (repo / ".git" / "hooks" / "pre-commit.legacy").read_bytes() == _HAND_WRITTEN_PRE_COMMIT
        assert probe_git_hooks(repo).ok

    def test_a_repair_that_never_runs_leaves_the_legacy_slot_alone(self, repo: Path) -> None:
        """The control: `probe.ok` short-circuits before `-f`, so this asserts nothing about it."""
        _install(repo)
        legacy = repo / ".git" / "hooks" / "pre-push.legacy"
        legacy.write_bytes(_HAND_WRITTEN_HOOK)
        legacy.chmod(0o755)

        _install(repo)

        assert legacy.read_bytes() == _HAND_WRITTEN_HOOK


def _quarantine(repo: Path) -> Path:
    return hook_quarantine.quarantine_dir(git_common_dir(repo))


def _parked(repo: Path, name: str) -> Path:
    return _quarantine(repo) / name


