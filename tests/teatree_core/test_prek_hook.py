        f"default_stages: [{stage}]\n"
        "repos:\n"
        "    - repo: local\n"
        "      hooks:\n"
        f"          - id: {hook_id}\n"
        f"            name: {hook_id}\n"
        "            language: system\n"
        "            entry: 'true'\n"
