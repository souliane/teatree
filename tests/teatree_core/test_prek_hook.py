def _park(repo: Path, body: str) -> dict[Path, bytes]:
    parked: dict[Path, bytes] = {}
    for name in _PARKED_COPIES:
        copy = _hooks_dir(repo) / name
        copy.write_text(body)
        copy.chmod(0o755)
        parked[copy] = copy.read_bytes()
    return parked


