"""Regression tests for prek pre-push hook stale-path coupling.

souliane/teatree#1462 — ``prek install`` bakes the install-time absolute path
of the binary into the SHARED ``.git/hooks/pre-push`` (``PREK="<abs>"``). The
hooks dir is shared across every worktree, so once the worktree that
provisioned it is torn down the baked path is stale and ``exec "$PREK"`` hangs
or fails for every sibling worktree. ``--no-verify`` became the workaround,
killing the pre-push gate.

Two complementary fixes are covered here.

Harden on install — after ``prek install`` the hook is rewritten so ``PREK``
resolves via PATH, never a baked absolute path. Version-independent: it holds
whether or not prek's own template carries a PATH fallback.

Reap on teardown — tearing down a worktree removes only the SHARED hooks baked
with a path inside that worktree, so the OTHER worktrees' pushes keep running
the hook to completion (the acceptance criterion).
"""

import logging
import os
import re
import shutil
import subprocess
from pathlib import Path
from unittest.mock import patch

import pytest

from teatree.core import prek_hook
from teatree.core.provision.provision_report import StepResult


def _vanished_cwd() -> str:
    raise FileNotFoundError(2, "No such file or directory")


_GIT_BIN = shutil.which("git") or "/usr/bin/git"

_STALE_PRE_PUSH = """#!/bin/sh
# File generated by prek: https://github.com/j178/prek
# ID: deadbeef

HERE="$(cd "$(dirname "$0")" && pwd)"
PREK="{prek_path}"

exec "$PREK" hook-impl --hook-dir "$HERE" --script-version 4 --hook-type=pre-push -- "$@"
"""


def _git(repo: Path, *args: str) -> None:
    subprocess.run([_GIT_BIN, "-C", str(repo), *args], check=True, capture_output=True)


@pytest.fixture
def main_clone(tmp_path: Path) -> Path:
    main = tmp_path / "main"
    main.mkdir()
    _git(main, "init", "--initial-branch=main", "-q")
    _git(main, "config", "user.email", "test@example.com")
    _git(main, "config", "user.name", "test")
    _git(main, "commit", "--allow-empty", "-m", "root")
    return main


def _hooks_dir(repo: Path) -> Path:
    proc = subprocess.run(
        [_GIT_BIN, "-C", str(repo), "rev-parse", "--git-path", "hooks"],
        check=True,
        capture_output=True,
        text=True,
    )
    hooks = Path(proc.stdout.strip())
    if not hooks.is_absolute():
        hooks = (repo / hooks).resolve()
    hooks.mkdir(parents=True, exist_ok=True)
    return hooks


def _write_stale_hook(repo: Path, name: str, prek_path: str) -> Path:
    hook = _hooks_dir(repo) / name
    hook.write_text(_STALE_PRE_PUSH.format(prek_path=prek_path))
    hook.chmod(0o755)
    return hook


class TestHardenHooks:
    def test_baked_absolute_path_rewritten_to_path_resolution(self, main_clone: Path) -> None:
        gone = main_clone.parent / "s-teatree-941-gone" / ".venv" / "bin" / "prek"
        hook = _write_stale_hook(main_clone, "pre-push", str(gone))

        prek_hook.harden_hooks(str(main_clone))

        body = hook.read_text()
        assert str(gone) not in body, f"stale absolute path survived hardening:\n{body}"
        assert 'PREK="prek"' in body, f"hook does not resolve prek via PATH:\n{body}"
        assert "hook-impl" in body, "hardening must not destroy the dispatch line"

    def test_idempotent_on_already_path_resolved_hook(self, main_clone: Path) -> None:
        hook = _write_stale_hook(main_clone, "pre-push", "prek")
        before = hook.read_text()

        prek_hook.harden_hooks(str(main_clone))

        assert hook.read_text() == before

    def test_leaves_non_prek_hooks_untouched(self, main_clone: Path) -> None:
        hook = _hooks_dir(main_clone) / "pre-push"
        custom = '#!/bin/sh\nPREK="/some/other/tool"\nexec "$PREK" "$@"\n'
        hook.write_text(custom)

        prek_hook.harden_hooks(str(main_clone))

        assert hook.read_text() == custom


class TestRemoveStaleHooks:
    def test_removes_shared_hook_baked_into_torn_down_worktree(self, main_clone: Path) -> None:
        torn = main_clone.parent / "torn-down-wt"
        hook = _write_stale_hook(main_clone, "pre-push", str(torn / ".venv" / "bin" / "prek"))

        cleaned = prek_hook.remove_stale_hooks(str(main_clone), str(torn))

        assert not hook.exists(), "stale hook baked into the torn-down worktree must be removed"
        assert str(hook) in cleaned

    def test_keeps_hook_baked_into_a_different_worktree(self, main_clone: Path) -> None:
        other = main_clone.parent / "still-alive-wt"
        hook = _write_stale_hook(main_clone, "pre-push", str(other / ".venv" / "bin" / "prek"))

        cleaned = prek_hook.remove_stale_hooks(str(main_clone), str(main_clone.parent / "torn-down-wt"))

        assert hook.exists(), "must not remove a hook coupled to a live sibling worktree"
        assert cleaned == []

    def test_keeps_path_resolved_hook(self, main_clone: Path) -> None:
        hook = _write_stale_hook(main_clone, "pre-push", "prek")

        cleaned = prek_hook.remove_stale_hooks(str(main_clone), str(main_clone.parent / "torn-down-wt"))

        assert hook.exists(), "a PATH-resolved hook is never stale and must survive any teardown"
        assert cleaned == []


class TestRemoveStaleHooksSurvivesVanishedAnchor:
    """souliane/teatree#2692 — a PATH-resolved hook must not crash teardown on a vanished CWD.

    Classifying a hook bakes its ``PREK=`` value through ``_is_within``. For a
    PATH-hardened hook that value is the relative ``"prek"`` (#1462), so
    ``Path("prek").resolve()`` resolves against ``os.getcwd()`` — which raises
    ``FileNotFoundError`` once the worktree the process is sitting in has been
    removed earlier in the same teardown. The throw aborted ``cleanup_worktree``
    before the DB drop / row delete / reap steps ran.
    """

    def test_keeps_path_resolved_hook_when_cwd_is_gone(self, main_clone: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        hook = _write_stale_hook(main_clone, "pre-push", "prek")
        monkeypatch.setattr(os, "getcwd", _vanished_cwd)

        cleaned = prek_hook.remove_stale_hooks(str(main_clone), str(main_clone.parent / "torn-down-wt"))

        assert hook.exists(), "PATH-resolved hook must survive teardown even with a vanished CWD"
        assert cleaned == []

    def test_is_within_relative_candidate_never_resolves(self, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.setattr(os, "getcwd", _vanished_cwd)

        assert prek_hook._is_within(Path("prek"), Path("/removed/worktree")) is False


def _noop_config(stage: str, hook_id: str) -> str:
    return (
        f"default_install_hook_types: [{stage}]\n"
        f"default_stages: [{stage}]\n"
        "repos:\n"
        "    - repo: local\n"
        "      hooks:\n"
        f"          - id: {hook_id}\n"
        f"            name: {hook_id}\n"
        "            language: system\n"
        "            entry: 'true'\n"
        "            pass_filenames: false\n"
        "            always_run: true\n"
    )


@pytest.mark.skipif(shutil.which("prek") is None, reason="prek not on PATH")
class TestInstallResolvesTheRepoRootConfig:
    """The repo's OWN config gates its commits, never a vendored project's.

    ``prek`` resolves its config from the CWD, and when that CWD is a
    subdirectory of the repo it bakes ``--cd=<subdir>`` into the generated shim.
    A repo that VENDORS another project which carries its own
    ``.pre-commit-config.yaml`` therefore has its entire gate replaced the
    moment provisioning installs from the vendored path: every one of the host
    repo's hooks stops running, the vendored project's development lane gates
    the host instead, and nothing reports the swap — the commits simply start
    failing on the vendored project's rules and passing none of the host's.
    """

    def test_installing_from_a_vendored_subdir_still_gates_on_the_root_config(self, main_clone: Path) -> None:
        (main_clone / ".pre-commit-config.yaml").write_text(_noop_config("pre-commit", "host-gate"))
        vendored = main_clone / "vendor" / "core"
        vendored.mkdir(parents=True)
        (vendored / ".pre-commit-config.yaml").write_text(_noop_config("pre-commit", "vendored-gate"))

        result = prek_hook.install(str(vendored))
        assert result.success, f"prek install failed: {result.error}"

        hook = _hooks_dir(main_clone) / "pre-commit"
        assert hook.is_file()
        body = hook.read_text()
        assert "--cd=" not in body, (
            "installed shim delegates to a nested config — the host repo's own gates are dark:\n" + body
        )


@pytest.mark.skipif(shutil.which("prek") is None, reason="prek not on PATH")
class TestInstallProducesPathResolvedHook:
    def test_install_hook_never_carries_a_stale_absolute_only_path(self, main_clone: Path) -> None:
        wt = main_clone.parent / "wt"
        _git(main_clone, "worktree", "add", "-q", str(wt), "-b", "feature/1462")
        (wt / ".pre-commit-config.yaml").write_text(
            "default_install_hook_types: [pre-push]\n"
            "default_stages: [pre-push]\n"
            "repos:\n"
            "    - repo: local\n"
            "      hooks:\n"
            "          - id: noop\n"
            "            name: noop\n"
            "            language: system\n"
            "            entry: 'true'\n"
            "            pass_filenames: false\n"
            "            always_run: true\n"
        )

        result = prek_hook.install(str(wt))
        assert result.success, f"prek install failed: {result.error}"

        hook = _hooks_dir(main_clone) / "pre-push"
        assert hook.is_file()
        # The PRIMARY assignment must resolve via PATH. prek's own template
        # bakes ``PREK="<abs>"`` and (in recent versions) adds a fallback that
        # also writes ``PREK="prek"`` — so a substring check passes even on the
        # buggy hook. Pin the primary assignment line itself.
        primary = next(
            (ln.strip() for ln in hook.read_text().splitlines() if re.fullmatch(r'PREK="[^"]*"', ln.strip())),
            "",
        )
        assert primary == 'PREK="prek"', (
            "installed hook's primary PREK assignment still bakes an absolute path — "
            f"stale-path hang class (souliane/teatree#1462):\n{hook.read_text()}"
        )


_FOREIGN_HOOK = """#!/bin/sh
# File generated by prek: https://github.com/j178/prek
# ID: cafebabe

HERE="$(cd "$(dirname "$0")" && pwd)"
PREK="prek"

exec "$PREK" hook-impl --cd=vendor/core --hook-dir "$HERE" --hook-type={name} -- "$@"
"""


def _write_foreign_hook(repo: Path, name: str) -> Path:
    hook = _hooks_dir(repo) / name
    hook.write_text(_FOREIGN_HOOK.format(name=name))
    hook.chmod(0o755)
    return hook


def _prek_install_returning(*, success: bool):
    """Force the ``prek install`` step's verdict while every git step still runs for real.

    ``prek_hook`` drives git through the same ``run_step``, so blanket-patching it would
    also blind the hooks-dir and repo-root lookups this behaviour depends on.
    """
    real = prek_hook.run_step

    def _dispatch(name: str, *args: object, **kwargs: object) -> StepResult:
        if name == "prek-install":
            return StepResult(name=name, success=success, error="" if success else "prek exploded")
        return real(name, *args, **kwargs)

    return _dispatch


class TestAFailedInstallLeavesTheGateNoWeaker:
    """A failed re-install must not silently un-gate every worktree of the clone (#4193).

    ``drop_foreign_config_hooks`` deletes from the clone's SHARED hooks dir, so the
    removal lands on every sibling worktree at once. It is only a repair because the
    install that follows rewrites what it removed — when that install fails, the
    unrestored deletion leaves the whole clone with no pre-commit / pre-push /
    commit-msg hook and nothing reporting it. A hook bound to the wrong config is a bad
    gate; no hook at all is no gate, and far quieter.
    """

    def test_hooks_are_restored_when_the_install_fails(self, main_clone: Path) -> None:
        bodies = {name: _write_foreign_hook(main_clone, name).read_text() for name in prek_hook._HOOK_NAMES}

        with patch.object(prek_hook, "run_step", side_effect=_prek_install_returning(success=False)):
            result = prek_hook.install(str(main_clone))

        assert not result.success
        for name, body in bodies.items():
            hook = _hooks_dir(main_clone) / name
            assert hook.is_file(), f"{name} was dropped for an install that failed and never put back"
            assert hook.read_text() == body
            assert os.access(hook, os.X_OK), f"{name} was restored without its executable bit"

    def test_a_successful_install_does_not_put_the_foreign_hooks_back(self, main_clone: Path) -> None:
        """The teeth: restoring on failure must not resurrect the shim a success removed."""
        _write_foreign_hook(main_clone, "commit-msg")

        with patch.object(prek_hook, "run_step", side_effect=_prek_install_returning(success=True)):
            result = prek_hook.install(str(main_clone))

        assert result.success
        assert not (_hooks_dir(main_clone) / "commit-msg").exists()

    def test_an_unrestorable_hook_is_logged_not_swallowed(
        self, main_clone: Path, caplog: pytest.LogCaptureFixture
    ) -> None:
        dropped = [prek_hook.DroppedHook(path=_hooks_dir(main_clone) / "nested" / "pre-commit", body="x", mode=0o755)]

        with caplog.at_level(logging.ERROR, logger=prek_hook.__name__):
            prek_hook._restore(dropped)

        assert "Could NOT restore" in caplog.text
