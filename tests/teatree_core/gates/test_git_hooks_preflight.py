class TestTheProbeCarriesTheQuarantine:
    """The doctor and the installer line read ONE computation, so they cannot disagree."""

    @staticmethod
    def _park(repo: Path, name: str, blob: bytes) -> Path:
        parked = hook_quarantine.quarantine_dir(git_common_dir(repo))
        parked.mkdir(parents=True, exist_ok=True)
        (parked / name).write_bytes(blob)
        return parked / name

    def test_a_clean_checkout_reports_nothing_parked(self, tmp_path: Path) -> None:
        repo = make_git_repo(tmp_path / "repo")

        assert probe_git_hooks(repo).quarantined == ()

    def test_a_parked_hook_is_reported_and_fails_the_remediation(self, tmp_path: Path) -> None:
        repo = make_git_repo(tmp_path / "repo")
        parked = self._park(repo, "pre-push", b"#!/bin/sh\nexit 0\n")

        probe = probe_git_hooks(repo)

        assert probe.quarantined == (parked,)
        assert any(str(parked) in line for line in format_remediation(probe)), format_remediation(probe)

    def test_an_unreadable_quarantine_is_none_and_still_reported(self, tmp_path: Path) -> None:
        repo = make_git_repo(tmp_path / "repo")
        hook_quarantine.quarantine_dir(git_common_dir(repo)).mkdir(parents=True)

        def _refuse(self: Path) -> None:
            raise PermissionError(13, "Permission denied", str(self))

        with patch.object(Path, "iterdir", _refuse):
            probe = probe_git_hooks(repo)

        assert probe.quarantined is None
        assert any(hook_quarantine.QUARANTINE_DIRNAME in line for line in format_remediation(probe))

    def test_the_two_findings_are_independent_sections(self, tmp_path: Path) -> None:
        """A fully-installed clone can still be holding a gate that is no longer running."""
        repo = make_git_repo(tmp_path / "repo")
        parked = self._park(repo, "pre-push", b"#!/bin/sh\nexit 0\n")

        lines = format_remediation(probe_git_hooks(repo))

        assert any("is not running its git hooks" in line for line in lines), lines
        assert any(str(parked) in line for line in lines), lines


class TestAMissingGitBinaryNeverPropagates:
    """`GitHooksInstaller.install` does not wrap this probe, and `t3 setup` runs under `set -e`.

    The canonical `git_common_dir` lets an `OSError` out — an unreachable binary would
    traceback out of container init instead of reporting one unprobeable checkout.
    """

    def test_a_missing_git_binary_reads_as_indeterminate_not_a_raise(self, tmp_path: Path) -> None:
        repo = make_git_repo(tmp_path / "repo")

        with patch.object(run_mod, "subprocess") as mock_sp:
            mock_sp.run.side_effect = FileNotFoundError(2, "No such file or directory", "git")
            probe = probe_git_hooks(repo)

        assert probe.indeterminate_reason is not None
        assert probe.hooks_dir is None

    def test_a_reachable_git_binary_still_probes_the_checkout(self, tmp_path: Path) -> None:
        """The control: a guard returning `None` unconditionally passes the test above."""
        repo = make_git_repo(tmp_path / "repo")

        probe = probe_git_hooks(repo)

        assert probe.indeterminate_reason is None
        assert probe.hooks_dir == (repo / ".git" / "hooks").resolve()


class TestTheDoctorStaysSilentOnAnUnprobeableCheckout:
    """The other polarity of the installer's "must speak": a line here is a hard doctor FAIL.

    ``checks_bootstrap._check_git_hooks_installed`` reads any remediation line as a failure, so
    emitting one for a checkout nothing could inspect attributes a cause the probe never found.
    """

    def test_format_remediation_stays_silent_on_an_unprobeable_checkout(self, tmp_path: Path) -> None:
        not_a_checkout = tmp_path / "plain"
        not_a_checkout.mkdir()
        probe = probe_git_hooks(not_a_checkout)
        assert probe.indeterminate_reason is not None, "the fixture turned out to be a checkout"

        assert format_remediation(probe) == []

    def test_format_remediation_still_reports_a_probeable_gap(self, tmp_path: Path) -> None:
        """The control: returning `[]` unconditionally passes the test above."""
        repo = make_git_repo(tmp_path / "repo")

        assert format_remediation(probe_git_hooks(repo)) != []
