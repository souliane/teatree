import logging
import re
import stat
from dataclasses import dataclass
from pathlib import Path

from teatree.core.provision.provision_report import StepResult
from teatree.core.provision.step_runner import run_step

logger = logging.getLogger(__name__)

_PREK_MARKER = "File generated by prek"
_HOOK_NAMES = ("pre-commit", "pre-push", "commit-msg")
_PREK_ASSIGNMENT_RE = re.compile(r'^PREK="([^"]*)"$', re.MULTILINE)
_FOREIGN_CONFIG_FLAG = "--cd="
_PATH_RESOLVED_PREK = 'PREK="prek"'


def _shared_hooks_dir(wt_path: str) -> Path | None:
    result = run_step(
        "git-hooks-path",
        ["git", "rev-parse", "--git-path", "hooks"],
        cwd=wt_path,
    )
    if not result.success or not result.stdout.strip():
        return None
    hooks_dir = Path(result.stdout.strip())
    if not hooks_dir.is_absolute():
        hooks_dir = (Path(wt_path) / hooks_dir).resolve()
    return hooks_dir


def _local_hooks_path(wt_path: str) -> str | None:
    """Return the LOCAL-scope ``core.hooksPath`` value, or ``None`` if unset.

    Reads ``--local`` only: a redundant value baked into the repo's own config
    (the #2706 footgun) is what blocks ``prek install``; a global/system
    ``core.hooksPath`` is the user's machine-wide intent and is never touched.
    """
    result = run_step(
        "git-hookspath-get",
        ["git", "config", "--local", "--get", "core.hooksPath"],
        cwd=wt_path,
    )
    value = result.stdout.strip()
    return value or None


def _default_hooks_dir(wt_path: str) -> Path | None:
    """The repo's DEFAULT hooks dir (``<git-common-dir>/hooks``).

    This is where git looks for hooks when ``core.hooksPath`` is unset — and
    where ``prek install`` writes. A ``core.hooksPath`` resolving here is
    redundant; one resolving elsewhere is a genuine custom override.
    """
    result = run_step(
        "git-common-dir",
        ["git", "rev-parse", "--git-common-dir"],
        cwd=wt_path,
    )
    if not result.success or not result.stdout.strip():
        return None
    common = Path(result.stdout.strip())
    if not common.is_absolute():
        common = (Path(wt_path) / common).resolve()
    return (common / "hooks").resolve()


def _clear_redundant_hooks_path(wt_path: str) -> bool:
    """Unset a LOCAL ``core.hooksPath`` that merely re-points at the default.

    ``prek install`` refuses ("Cowardly refusing to install hooks with
    ``core.hooksPath`` set") whenever the key is present, even when its value
    equals git's own default hooks dir — so a redundant value left by an IDE
    or a stale setup silently disables every commit/push hook (#2706). When
    the local value resolves to the default hooks dir it carries no intent, so
    we unset it (local scope only) and let ``prek install`` proceed. A value
    pointing ELSEWHERE is a real custom override and is left untouched.

    Returns ``True`` when a redundant value was unset.
    """
    configured = _local_hooks_path(wt_path)
    if configured is None:
        return False
    default = _default_hooks_dir(wt_path)
    if default is None:
        return False
    if Path(configured).resolve() != default:
        return False  # genuine custom hooksPath — preserve the user's intent
    result = run_step(
        "git-hookspath-unset",
        ["git", "config", "--local", "--unset", "core.hooksPath"],
        cwd=wt_path,
    )
    if result.success:
        logger.info("Unset redundant local core.hooksPath (== default hooks dir) so prek can install")
    return result.success


def _is_prek_hook(path: Path) -> bool:
    return path.is_file() and _PREK_MARKER in _read(path)


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return ""


def _baked_prek_path(body: str) -> str | None:
    match = _PREK_ASSIGNMENT_RE.search(body)
    return match.group(1) if match else None


def _install_cwd(wt_path: str) -> str:
    """The worktree ROOT ``prek install`` must run from, never a subdirectory.

    ``prek`` resolves its config from the CWD and, when that CWD is a
    subdirectory of the repo, bakes ``--cd=<subdir>`` into the generated shim —
    so the repo's commit gate becomes that subdirectory's config. A repo that
    VENDORS another project carrying its own ``.pre-commit-config.yaml``
    (``<host>/vendor/<core>``) has its ENTIRE gate replaced the moment
    provisioning is pointed at the vendored path: every host hook stops running
    and the vendored project's development lane gates the host instead. Nothing
    reports the swap — commits just start failing on rules the host never
    adopted and passing none of the ones it did.
    """
    result = run_step("git-toplevel", ["git", "rev-parse", "--show-toplevel"], cwd=wt_path)
    if not result.success or not result.stdout.strip():
        return wt_path
    return result.stdout.strip()


@dataclass(frozen=True, slots=True)
class DroppedHook:
    """One prek shim removed ahead of a re-install, kept whole so it can be put back."""

    path: Path
    body: str
    mode: int

    def restore(self) -> None:
        self.path.write_text(self.body, encoding="utf-8")
        self.path.chmod(self.mode)
        logger.warning("Restored the prek hook removed for a failed re-install: %s", self.path)


def drop_foreign_config_hooks(wt_path: str) -> list[DroppedHook]:
    """Remove prek shims bound to a config other than the repo root's.

    ``prek install`` bakes ``--cd=<subdir>`` when it runs from below the repo
    root, and the shim then gates the repo on that subdirectory's config. Running
    the install from the root fixes every hook type the root config DECLARES,
    because each one is overwritten. A type it does not declare is never written
    again, so a shim installed once from a vendored subdir survives the repair
    indefinitely and keeps running the vendored project's lane. Removing it
    BEFORE the install is what lets the repair reach it: a declared type is then
    rewritten correctly, and an undeclared one is simply gone.

    Each removal is returned WHOLE (body + mode), not merely named, because these
    hooks live in the clone's SHARED hooks dir: the removal reaches every sibling
    worktree at once, and until the install that justifies it succeeds the deletion is
    not a repair but an outage. :func:`install` puts them back when it fails.
    """
    hooks_dir = _shared_hooks_dir(wt_path)
    if hooks_dir is None:
        return []
    dropped: list[DroppedHook] = []
    for name in _HOOK_NAMES:
        hook = hooks_dir / name
        if not _is_prek_hook(hook) or _FOREIGN_CONFIG_FLAG not in _read(hook):
            continue
        dropped.append(DroppedHook(path=hook, body=_read(hook), mode=stat.S_IMODE(hook.stat().st_mode)))
        hook.unlink()
        logger.info("Removed prek hook bound to a non-root config: %s", hook)
    return dropped


def install(wt_path: str) -> StepResult:
    """Install the repo-root prek hooks, leaving the gate no weaker than it was found.

    The drop below is only safe because the install that follows rewrites what it
    removed. When the install FAILS the removal has to be undone: the hooks are the
    clone's SHARED ones, so an unrepaired drop leaves EVERY sibling worktree of that
    clone with no pre-commit / pre-push / commit-msg hook at all, and nothing says so —
    commits and pushes simply stop being gated. A shim bound to the wrong config is a
    bad gate; no shim at all is no gate, which is strictly worse and far quieter.
    """
    _clear_redundant_hooks_path(wt_path)
    dropped = drop_foreign_config_hooks(wt_path)
    # A RAISED install leaves the clone exactly as ungated as a failed one — the binary
    # missing, the cwd gone, the subprocess timing out — so both paths restore. Not a
    # bare ``finally``: on SUCCESS the drop is precisely what the install replaced, and
    # putting the old shims back would undo the repair.
    try:
        result = run_step("prek-install", ["prek", "install", "-f"], cwd=_install_cwd(wt_path))
    except BaseException:
        _restore(dropped)
        raise
    if not result.success:
        _restore(dropped)
        return result
    harden_hooks(wt_path)
    return result


def _restore(dropped: list[DroppedHook]) -> None:
    """Put back every hook the failed install was supposed to have replaced.

    Restoring is itself best-effort — a hooks dir that has become unwritable cannot be
    repaired from here — but a failure to restore is LOUD, because it is the state in
    which the clone is left ungated.
    """
    for hook in dropped:
        try:
            hook.restore()
        except OSError:
            logger.exception(
                "Could NOT restore the prek hook %s after a failed install — every worktree of this "
                "clone is now missing that hook and its commit/push gate is dark until `t3` re-provisions.",
                hook.path,
            )


def harden_hooks(wt_path: str) -> None:
    """Rewrite prek-generated hooks so ``prek`` resolves via PATH, not a baked path.

    ``prek install`` bakes the install-time absolute path of the binary into
    ``PREK="<abs>"``. That path belongs to whichever worktree provisioned the
    SHARED ``.git/hooks`` last; once that worktree is torn down the absolute
    path is stale and ``exec "$PREK"`` hangs or fails for every other worktree
    (souliane/teatree#1462). Resolving via PATH removes the worktree coupling.
    """
    hooks_dir = _shared_hooks_dir(wt_path)
    if hooks_dir is None:
        return
    for name in _HOOK_NAMES:
        hook = hooks_dir / name
        if not _is_prek_hook(hook):
            continue
        body = _read(hook)
        hardened = _PREK_ASSIGNMENT_RE.sub(_PATH_RESOLVED_PREK, body)
        if hardened != body:
            hook.write_text(hardened, encoding="utf-8")
            logger.info("Hardened prek hook to resolve via PATH: %s", hook)


def remove_stale_hooks(wt_path: str, removed_dir: str) -> list[str]:
    """Remove SHARED prek hooks whose baked ``PREK=`` path lives in ``removed_dir``.

    The pre-push/pre-commit hooks live in the SHARED git common dir, so a hook
    baked with a path inside a torn-down worktree poisons every sibling
    worktree (souliane/teatree#1462). Teardown removes only the hooks coupled
    to the worktree being removed; PATH-resolved hooks are left untouched.
    """
    hooks_dir = _shared_hooks_dir(wt_path)
    if hooks_dir is None:
        return []
    removed = Path(removed_dir).resolve()
    cleaned: list[str] = []
    for name in _HOOK_NAMES:
        hook = hooks_dir / name
        if not _is_prek_hook(hook):
            continue
        baked = _baked_prek_path(_read(hook))
        if baked and _is_within(Path(baked), removed):
            hook.unlink()
            cleaned.append(str(hook))
            logger.info("Removed stale prek hook pointing into %s: %s", removed, hook)
    return cleaned


def _is_within(candidate: Path, parent: Path) -> bool:
    # A PATH-resolved hook bakes the relative ``PREK="prek"`` (#1462); that is a
    # PATH lookup, never a filesystem path inside ``parent``, so it is never
    # "within". Short-circuiting also avoids ``resolve()`` anchoring a relative
    # path against ``os.getcwd()`` — which raises FileNotFoundError once the
    # worktree the process sits in has vanished mid-teardown (#2692).
    if not candidate.is_absolute():
        return False
    try:
        candidate.resolve().relative_to(parent)
    except ValueError:
        return False
    return True
